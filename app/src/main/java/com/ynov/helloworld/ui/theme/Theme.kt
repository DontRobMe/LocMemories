// region Thème

/**
 * Thème de l'application : couleurs teal, typographie et formes personnalisées.
 *
 * @param darkTheme force le thème sombre ; suit le réglage système par défaut.
 * @param dynamicColor utilise les couleurs du fond d'écran (Material You, Android 12+).
 *   Désactivé par défaut pour conserver l'identité visuelle teal.
 */
@Composable
fun HelloWorldTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = AppShapes,
        content = content
    )
}

